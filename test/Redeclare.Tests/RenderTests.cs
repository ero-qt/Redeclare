    [Test]
    public void HintName_NamespacesAroundOneType_NamesTheFileAfterIt()
    {
        var sole = new CompilationUnit(Members: [new NamespaceDeclaration(Name: "A", Members: [new TypeDeclaration(Name: "X")])]);
        var crowded = new CompilationUnit(
            Members: [new NamespaceDeclaration(Name: "A", Members: [new TypeDeclaration(Name: "X"), new TypeDeclaration(Name: "Y")])]);

        using (Assert.EnterMultipleScope())
        {
            Assert.That(sole.HintName, Is.EqualTo("A.X.g.cs"));
            Assert.That(crowded.HintName, Is.EqualTo("Generated.g.cs"), "a namespace holding two types names no single file");
            Assert.That(new CompilationUnit().HintName, Is.EqualTo("Generated.g.cs"));
        }
    }

    [Test]
    public void Render_TypeWithContainingType_WritesPartialPartsAroundIt()
    {
        var outer = new TypeDeclaration(Name: "Outer", TypeParameters: [new TypeParameterDeclaration(Name: "T")]);
        var inner = new TypeDeclaration(
            Name: "Inner",
            Accessibility: Accessibility.Public,
            ContainingType: outer,
            Members: [new FieldDeclaration(Type: Types.Int32, Name: "x")]);
        var renamed = inner with { Name = "Renamed" };
        var unit = new CompilationUnit(Members: [new NamespaceDeclaration(Name: "N", Members: [inner])], Header: Header);

        using (Assert.EnterMultipleScope())
        {
            Assert.That(unit.HintName, Is.EqualTo("N.Outer`1.Inner.g.cs"), "the name follows what it is declared in");
            Assert.That(renamed.ContainingType, Is.EqualTo(outer), "editing the type leaves what it is in alone");
            Assert.That(unit.Render(), Does.Contain("partial class Outer<T>\n{\n    public class Inner\n    {\n        int x;\n    }\n}"));
        }
    }

