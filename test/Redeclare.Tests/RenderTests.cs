    [Test]
    public void Render_SeveralNamespacesAndTypes_UsesBlocksAndNestsThem()
    {
        var file = new CompilationUnit(
            Members: [
                new TypeDeclaration(Name: "Global"),
                new NamespaceDeclaration(
                    Name: "A",
                    Members: [
                        new TypeDeclaration(Name: "InA"),
                        new NamespaceDeclaration(Name: "B.C", Members: [new TypeDeclaration(Name: "InBC")]),
                    ]),
                new NamespaceDeclaration(Name: "D", Members: [new TypeDeclaration(TypeKind: TypeKind.Struct, Name: "InD")]),
            ],
            Header: Header);

        string text = file.Render(RenderOptions.Default);
        Compiling.AssertCompiles(text);

        using (Assert.EnterMultipleScope())
        {
            Assert.That(text, Does.Contain("class Global"));
            Assert.That(text, Does.Contain("namespace A\n{"));
            Assert.That(text, Does.Contain("    namespace B.C\n    {"));
            Assert.That(text, Does.Contain("        class InBC"));
            Assert.That(text, Does.Contain("namespace D\n{"));
            Assert.That(text, Does.Not.Contain("namespace A;"), "three members, so no file-scoped namespace");
        }
    }

