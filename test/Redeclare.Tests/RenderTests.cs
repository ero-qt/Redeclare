    [Test]
    public void Render_DelegateRefMembersAndEventAccessors_Compile()
    {
        var markAttribute = new NamedTypeReference(Name: "MarkAttribute", ContainingNamespace: "Sample");
        var unit = new CompilationUnit(
            Members: [
                new NamespaceDeclaration(
                    Name: "Sample",
                    Members: [
                    new TypeDeclaration(
                        Accessibility: Accessibility.Public,
                        Name: "Callback",
                        TypeKind: TypeKind.Delegate,
                        TypeParameters: [new TypeParameterDeclaration(Name: "T", HasValueTypeConstraint: true)],
                        ReturnType: Types.Boolean,
                        ParameterList: [
                            new ParameterDeclaration(Type: Types.T, Name: "value"),
                            new ParameterDeclaration(RefKind: RefKind.Out, Type: Types.String, Name: "text"),
                        ]),
                    new TypeDeclaration(
                        Accessibility: Accessibility.Public,
                        Modifiers: Modifiers.Ref,
                        TypeKind: TypeKind.Struct,
                        Name: "Holder",
                        TypeParameters: [new TypeParameterDeclaration(Name: "T", Attributes: [new AttributeSpecification(Type: markAttribute)])],
                        Members: [
                            new FieldDeclaration(Accessibility: Accessibility.Public, RefKind: RefKind.Ref, Type: Types.Int32, Name: "Slot"),
                            new PropertyDeclaration(
                                Accessibility: Accessibility.Public,
                                RefKind: RefKind.RefReadOnly,
                                Type: Types.Int32,
                                Name: "Value",
                                Getter: new AccessorDeclaration(Body: Snippet.Expression("ref Slot")),
                                Setter: null),
                            new MethodDeclaration(
                                Accessibility: Accessibility.Public,
                                RefKind: RefKind.Ref,
                                ReturnType: Types.Int32,
                                Name: "Borrow",
                                Body: Snippet.Expression("ref Slot")),
                            new EventDeclaration(
                                Accessibility: Accessibility.Public,
                                Type: Types.Action,
                                Name: "Changed",
                                Adder: new AccessorDeclaration(Body: "_ = value;"),
                                Remover: new AccessorDeclaration(Body: "_ = value;")),
                        ]),
                ]),
            ],
            Header: Header);

        string text = unit.Render(RenderOptions.Default);
        Compiling.AssertCompiles(text, LanguageVersion.Latest, "namespace Sample { public sealed class MarkAttribute : System.Attribute { } }");

        using (Assert.EnterMultipleScope())
        {
            Assert.That(text, Does.Contain("public delegate bool Callback<T>(T value, out string text) where T : struct;"));
            Assert.That(text, Does.Contain("public ref struct Holder<[global::Sample.MarkAttribute] T>"));
            Assert.That(text, Does.Contain("public ref int Slot;"));
            Assert.That(text, Does.Contain("public ref readonly int Value => ref Slot;"));
            Assert.That(text, Does.Contain("public ref int Borrow()"));
            Assert.That(
                text,
                Does.Contain("public event global::System.Action Changed\n    {\n        add\n        {\n            _ = value;\n        }"));
        }
    }

