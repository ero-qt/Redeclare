    [Test]
    public void Render_StaticPropertyWithMultiLineInitializer_WritesTheWholeFile()
    {
        var options = new NamedTypeReference(Name: "Options", ContainingNamespace: "My");
        var sectionShape = new NamedTypeReference(Name: "SectionShape", ContainingType: options);
        var nested = new NamedTypeReference(Name: "Nested", ContainingNamespace: "My");
        var shape = new PropertyDeclaration(
            DocumentationComment: """
                <summary>
                    Gets the options the type declares.
                </summary>
                """,
            Accessibility: Accessibility.Internal,
            Modifiers: Modifiers.Static | Modifiers.New,
            Type: sectionShape,
            Name: "Shape",
            Initializer: Snippet.From($"""
                new(
                    ("timeout", null),
                    ("nested", {nested}.Shape))
                """),
            Getter: new AccessorDeclaration(),
            Setter: null);
        var unit = new CompilationUnit(
            Members: [
                new NamespaceDeclaration(
                    Name: "My",
                    Members: [new TypeDeclaration(Name: "Options", Modifiers: Modifiers.Partial, Members: [shape])]),
            ],
            Header: Header);

        Assert.That(unit.Render(), Is.EqualTo("""
            // <auto-generated/>

            #nullable enable

            namespace My;

            partial class Options
            {
                /// <summary>
                ///     Gets the options the type declares.
                /// </summary>
                internal static new global::My.Options.SectionShape Shape { get; } = new(
                    ("timeout", null),
                    ("nested", global::My.Nested.Shape));
            }

            """.ReplaceLineEndings("\n")));
    }

